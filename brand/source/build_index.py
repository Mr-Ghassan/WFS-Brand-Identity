"""Generate brand/WFS_BRAND_ASSET_INDEX.md from the build records and the file tree."""
import os, json, glob, re
import brand_config as B

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
M = os.path.join(ROOT, 'source', 'master')
load = lambda n: json.load(open(os.path.join(M, n))) if os.path.exists(os.path.join(M, n)) else []
logos, apps, gfx, extras = load('asset_records_logos.json'), load('asset_records_appicons.json'), load('asset_records_graphics.json'), load('asset_records_extras.json')

def count(pat): return len(glob.glob(os.path.join(ROOT, pat), recursive=True))
n_svg = count('**/*.svg') - count('source/node_modules/**/*.svg')
n_png = count('**/*.png') - count('source/node_modules/**/*.png')
n_pdf = count('**/*.pdf')
logo_files = [f for g in ('logo', 'icon', 'wordmark') for f in glob.glob(os.path.join(ROOT, g, '**', '*.*'), recursive=True) if not f.endswith('.md')]

L = []
L.append(f'# WFS Brand Asset Index — Brand Identity {B.VERSION} ({B.YEAR})\n')
L.append('WFS — Wusool Financial System · نظام وصول المالي · A WUSOOL Tech Product\n')
L.append('Every production file in `brand/`, with purpose, format, variant, colourway and background compatibility. '
         'Generated by `source/build_index.py` — do not edit by hand.\n')
L.append('## Summary\n')
L.append('| Item | Count |\n|---|---|')
L.append(f'| Logo / icon / wordmark master variants | {len(logos)} (each as SVG + vector PDF + transparent PNG set) |')
L.append(f'| Files in logo/, icon/, wordmark/ (excl. README) | {len(logo_files)} |')
L.append(f'| SVG files (whole package) | {n_svg} |')
L.append(f'| PNG files (whole package) | {n_png} |')
L.append(f'| PDF files (whole package) | {n_pdf} |')
L.append('| Native AI files | 0 — requires Adobe Illustrator; run `source/illustrator/export_ai.jsx` (see `logo/ai/README.md`) |')
L.append('')
L.append('## Conventions\n')
L.append('- **Naming:** `WFS_[Asset]_[Layout]_[Colourway]_[size]px.[ext]`')
L.append('- **Colourways:** `Primary` full colour for light grounds · `Inverse` full colour for dark grounds · `Dark` / `White` / `Black` / `Teal` one colour · `Monochrome` greyscale tonal (light grounds) · `Monochrome_Light` greyscale tonal (dark grounds) · `Premium` dimensional display version (dark grounds) · `Premium_Light` (light grounds)')
L.append('- **PNG** logo files are transparent; sizes are the *width* for lockups/wordmarks and the *height* for icons.')
L.append('- **SVG** masters: outlined paths only, no embedded rasters, no live text, no editor metadata. **PDF**: single-page vector.')
L.append('- Core colours: ' + ' · '.join(f'`{v["hex"]}` {v["name"]}' for v in B.CORE.values()))
L.append('')

def table(recs, title):
    L.append(f'## {title}\n')
    L.append('| Asset | Purpose | Formats | Variant | Colour | Backgrounds |\n|---|---|---|---|---|---|')
    for r in recs:
        fm = []
        if r.get('svg'): fm.append(f'[SVG]({r["svg"]})')
        if r.get('pdf'): fm.append(f'[PDF]({r["pdf"]})')
        if r.get('png'):
            sizes = [re.search(r'_(\d+)px', p).group(1) for p in r['png']]
            fm.append('PNG ' + '/'.join(sizes))
        if r.get('format'): fm.append(r['format'])
        if r.get('files'): fm.append(', '.join(f'[{os.path.splitext(f)[1][1:].upper()}]({f})' for f in r['files']))
        L.append(f'| `{r["asset"]}` | {r.get("purpose", "")} | {" · ".join(fm)} | {r.get("variant", "")} | {r.get("colour", "")} | {r.get("backgrounds", "")} |')
    L.append('')

table([r for r in logos if r['group'] == 'icon'], 'Icon')
table([r for r in logos if r['group'] == 'wordmark'], 'Wordmark')
table([r for r in logos if r['group'] == 'logo'], 'Logo lockups')
table(apps, 'App icon & favicon')
table(gfx, 'Graphic system')
table(extras, 'Colour, typography, motion, templates, AI')
L.append('## Not included (and why)\n')
L.append('- `WFS_Wordmark_Dark` / `WFS_Wordmark_Monochrome`: the wordmark is one colour by construction — the primary wordmark **is** WFS Dark, and the monochrome wordmark **is** `WFS_Wordmark_Black`. Exporting aliases would create duplicate files.')
L.append('- `WFS_Logo_Full_Bilingual`: requires the licensed **Myriad Arabic** font to outline the Arabic descriptor. It was not available in the build environment; no substitute font was used. Add the font to `$WFS_FONT_DIR` and run `source/build_all.sh` to generate it.')
L.append('- Native `.ai`: see above.\n')
L.append('## Guidelines & sources\n')
L.append('- `guidelines/WFS_Brand_Guidelines_2026.pdf` — A4 landscape, 40 pages · `guidelines/source/` HTML + builder · `guidelines/preview/` page PNGs')
L.append('- `source/master/icon_geometry.json`, `source/master/wordmark_geometry.json` — numeric vector masters (circles, biarcs, paths)')
L.append('- `source/reference/` — the approved raster artwork the masters were reconstructed from')
L.append('- `source/qa/QA_REPORT.md` — automated validation results')
open(os.path.join(ROOT, 'WFS_BRAND_ASSET_INDEX.md'), 'w').write('\n'.join(L) + '\n')
print('index written:', len(L), 'lines')
